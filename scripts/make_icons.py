#!/usr/bin/env python3
"""Generates the OpenPS icon set from one geometry: PNGs, icns, ico and an SVG (dist/logo.svg).
Run from openps-rs/:  python3 scripts/make_icons.py     (needs Pillow; iconutil on macOS for the icns)"""
import os, subprocess, shutil
from PIL import Image, ImageDraw, ImageFilter

S = 4096                      # master canvas; geometry below is in a 1024 box and scaled
K = S / 1024
BG0, BG1 = (12, 18, 40), (30, 28, 64)         # tile gradient (top-left -> bottom-right)
EDGE = (64, 110, 235)                         # tile edge line
BLUE = (59, 130, 255)                         # console glyph
BODY, RADIUS = 824, 200                       # tile size in the 1024 grid (Apple's template margin) and corner radius
PILL = (430, 318, 594, 690)                   # console body x0, y0, x1, y1
SLOT = (480, 368, 544, 640)                   # dark slot inside it
BASE = (426, 706, 598, 738)                   # stand

def box(b, k=K):
    return [v * k for v in b]

def gradient(size, a, b):
    from PIL import ImageChops
    gy = Image.linear_gradient("L").resize((size, size))
    gx = gy.transpose(Image.TRANSPOSE)
    g = ImageChops.add(gx, gy, scale=2)
    return Image.composite(Image.new("RGB", (size, size), b), Image.new("RGB", (size, size), a), g)

def tile_box():
    m = (1024 - BODY) / 2
    return (m, m, m + BODY, m + BODY)

def master():
    base = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    mask = Image.new("L", (S, S), 0)
    ImageDraw.Draw(mask).rounded_rectangle(box(tile_box()), radius=RADIUS * K, fill=255)
    body = gradient(S, BG0, BG1).convert("RGBA")
    glow = Image.new("L", (S, S), 0)
    ImageDraw.Draw(glow).ellipse(box((512 - 300, 512 - 300, 512 + 300, 512 + 300)), fill=120)
    glow = glow.filter(ImageFilter.GaussianBlur(130 * K))
    body = Image.composite(Image.new("RGBA", (S, S), (50, 100, 235, 255)), body, glow)
    base.paste(body, (0, 0), mask)
    # edge line: the mask minus a slightly smaller copy
    inner = Image.new("L", (S, S), 0)
    t = tile_box()
    ImageDraw.Draw(inner).rounded_rectangle(box((t[0] + 5, t[1] + 5, t[2] - 5, t[3] - 5)), radius=(RADIUS - 5) * K, fill=255)
    from PIL import ImageChops
    edge = ImageChops.subtract(mask, inner).point(lambda v: v * 0.55)
    base.paste(Image.new("RGBA", (S, S), EDGE + (255,)), (0, 0), edge)
    # glyph
    d = ImageDraw.Draw(base)
    d.rounded_rectangle(box(PILL), radius=(PILL[2] - PILL[0]) / 2 * K, fill=BLUE + (255,))
    slot_col = (22, 26, 58, 255)
    d.rounded_rectangle(box(SLOT), radius=(SLOT[2] - SLOT[0]) / 2 * K, fill=slot_col)
    d.rounded_rectangle(box(BASE), radius=(BASE[3] - BASE[1]) / 2 * K, fill=BLUE + (255,))
    return base

def rrect(b, r, fill, extra=""):
    return f'<rect x="{b[0]}" y="{b[1]}" width="{b[2] - b[0]}" height="{b[3] - b[1]}" rx="{r}" fill="{fill}"{extra}/>'

def svg():
    t = tile_box()
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" role="img" aria-label="OpenPS">
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="rgb{BG0}"/><stop offset="1" stop-color="rgb{BG1}"/></linearGradient>
    <radialGradient id="glow"><stop offset="0" stop-color="rgb(50,100,235)" stop-opacity=".5"/><stop offset="1" stop-color="rgb(50,100,235)" stop-opacity="0"/></radialGradient>
  </defs>
  {rrect(t, RADIUS, "url(#bg)")}
  <circle cx="512" cy="512" r="330" fill="url(#glow)"/>
  <rect x="{t[0] + 2.5}" y="{t[1] + 2.5}" width="{BODY - 5}" height="{BODY - 5}" rx="{RADIUS - 2.5}" fill="none" stroke="rgb{EDGE}" stroke-opacity=".55" stroke-width="5"/>
  {rrect(PILL, (PILL[2] - PILL[0]) / 2, "rgb" + str(BLUE))}
  {rrect(SLOT, (SLOT[2] - SLOT[0]) / 2, "rgb(22,26,58)")}
  {rrect(BASE, (BASE[3] - BASE[1]) / 2, "rgb" + str(BLUE))}
</svg>
'''

def css():
    p = lambda v: f"{v / 10.24:.3f}%"
    t = tile_box()
    def place(b):
        return f"left: {p(b[0])}; top: {p(b[1])}; width: {p(b[2] - b[0])}; height: {p(b[3] - b[1])};"
    return f'''/* OpenPS logo drawn in pure CSS (generated by scripts/make_icons.py: do not edit by hand).
   Usage: <span class="ops-logo" role="img" aria-label="OpenPS"></span>   size it with width/height or font-size (1em). */
.ops-logo {{ position: relative; display: inline-block; width: 1em; height: 1em; font-size: 2rem; flex: none; }}
.ops-logo::before {{ /* tile: dark gradient, blue glow, thin blue edge */
  content: ""; position: absolute; {place(t)} border-radius: {RADIUS / BODY * 100:.2f}% / {RADIUS / BODY * 100:.2f}%;
  background: radial-gradient(circle at 50% 50%, rgba(50, 100, 235, .5), rgba(50, 100, 235, 0) 60%), linear-gradient(135deg, rgb{BG0}, rgb{BG1});
  box-shadow: inset 0 0 0 .5px rgba{EDGE[:3] + (.55,)}; }}
.ops-logo::after {{ /* console body with its slot */
  content: ""; position: absolute; {place(PILL)} border-radius: 999px; box-sizing: border-box;
  background: linear-gradient(rgb(22, 26, 58), rgb(22, 26, 58)) {(SLOT[0] - PILL[0]) / (PILL[2] - PILL[0]) * 100:.2f}% {(SLOT[1] - PILL[1]) / (PILL[3] - PILL[1]) * 100:.2f}% / {(SLOT[2] - SLOT[0]) / (PILL[2] - PILL[0]) * 100:.2f}% {(SLOT[3] - SLOT[1]) / (PILL[3] - PILL[1]) * 100:.2f}% no-repeat, rgb{BLUE}; }}
.ops-logo > i {{ position: absolute; display: block; }}
.ops-logo > .cap {{ display: none; }}
.ops-logo > .play {{ {place(BASE)} border-radius: 999px; background: rgb{BLUE}; }}
'''

def main():
    m = master()
    out = "src-tauri/icons"
    def save(size, name):
        m.resize((size, size), Image.LANCZOS).save(f"{out}/{name}")
    save(1024, "icon.png")
    for s, n in [(32, "32x32.png"), (128, "128x128.png"), (256, "128x128@2x.png"), (30, "Square30x30Logo.png"), (44, "Square44x44Logo.png"),
                 (71, "Square71x71Logo.png"), (89, "Square89x89Logo.png"), (107, "Square107x107Logo.png"), (142, "Square142x142Logo.png"),
                 (150, "Square150x150Logo.png"), (284, "Square284x284Logo.png"), (310, "Square310x310Logo.png"), (50, "StoreLogo.png")]:
        save(s, n)
    m.resize((256, 256), Image.LANCZOS).save(f"{out}/icon.ico", sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
    iset = "target/icon.iconset"
    shutil.rmtree(iset, ignore_errors=True); os.makedirs(iset)
    for s in (16, 32, 128, 256, 512):
        m.resize((s, s), Image.LANCZOS).save(f"{iset}/icon_{s}x{s}.png")
        m.resize((s * 2, s * 2), Image.LANCZOS).save(f"{iset}/icon_{s}x{s}@2x.png")
    subprocess.run(["iconutil", "-c", "icns", iset, "-o", f"{out}/icon.icns"], check=True)
    open("dist/logo.svg", "w").write(svg())
    open("dist/logo.css", "w").write(css())
    # menu-bar / small contexts: the mark alone is not needed yet; keep one source of truth
    print("ok")
main()
