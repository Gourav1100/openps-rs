#!/usr/bin/env python3
"""Downloads the UI icons from Lucide (https://lucide.dev, ISC licence) into assets/icons/lucide/ and rebuilds the icon sprite inside
dist/index.html (between the `icons:begin` and `icons:end` markers). Run from openps-rs/:  python3 scripts/fetch_icons.py
The app itself never fetches icons at run time: they are part of the page."""
import re, sys, urllib.request, pathlib

BASE = "https://cdn.jsdelivr.net/npm/lucide-static@latest/icons"
LICENSE = "https://raw.githubusercontent.com/lucide-icons/lucide/main/LICENSE"
# our sprite id -> Lucide icon name
ICONS = {
    "console": "monitor", "gear": "settings", "pulse": "activity", "info": "info", "play": "play", "power": "power",
    "trash": "trash-2", "expand": "maximize", "volume": "volume-2", "mute": "volume-x", "gamepad": "gamepad-2", "close": "x",
    "check": "check", "alert": "triangle-alert", "user": "user", "copy": "copy", "plus": "plus", "refresh": "refresh-cw",
    "chev-l": "chevron-left", "chev-r": "chevron-right", "trophy": "trophy",
    "foot": "footprints", "car": "car", "menu": "menu",  # the key mode shown over the stream (on foot, in a vehicle, in a menu)
}
root = pathlib.Path(__file__).resolve().parent.parent
out = root / "assets/icons/lucide"
out.mkdir(parents=True, exist_ok=True)

def get(url):
    with urllib.request.urlopen(url, timeout=30) as r:
        return r.read().decode()

(out / "LICENSE").write_text(get(LICENSE))
symbols = []
for sid, name in ICONS.items():
    svg = get(f"{BASE}/{name}.svg")
    (out / f"{name}.svg").write_text(svg)
    inner = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1)
    inner = re.sub(r"<!--.*?-->", "", inner, flags=re.S)
    inner = re.sub(r"\s+", " ", inner).strip()
    fill = ' fill="currentColor"' if sid in ("play", "trophy") else ' fill="none"'  # the play arrow reads better solid
    symbols.append(f'    <symbol id="{"g" if sid == "trophy" else "i"}-{sid}" viewBox="0 0 24 24"{fill} stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">{inner}</symbol>')

html = root / "dist/index.html"
text = html.read_text()
block = "    <!-- icons:begin (generated by scripts/fetch_icons.py from Lucide, ISC licence: assets/icons/lucide/LICENSE) -->\n" + "\n".join(symbols) + "\n    <!-- icons:end -->\n"
if "icons:begin" in text:
    text = re.sub(r"    <!-- icons:begin.*?<!-- icons:end -->\n", lambda m: block, text, flags=re.S)
else:
    # first run: drop the hand-drawn versions of these ids, then add the generated block before the first remaining symbol
    for sid in ICONS:
        pid = ("g" if sid == "trophy" else "i") + "-" + sid
        text = re.sub(r'    <symbol id="%s".*?</symbol>\n' % re.escape(pid), "", text, flags=re.S)
    i = text.index("    <symbol ")
    text = text[:i] + block + text[i:]
html.write_text(text)
print(f"{len(symbols)} icons written; sprite rebuilt")
